const allPieces = PUSH_LIBRARY.reduce((sum, theme) => sum + theme.titles.length * theme.bodies.length, 0);
export const PUSH_LIBRARY_SIZE = allPieces;

/** İsteme en uygun temalardan örnek bildirimler (yapay zekâ için üslup örneği) */
export const pickLibraryExamples = (prompt = "", { count = 4, seed = Date.now() } = {}) => {
  const text = String(prompt).toLocaleLowerCase("tr-TR");
  const scored = PUSH_LIBRARY
    .map((theme) => ({ theme, score: theme.keywords.filter((k) => text.includes(k)).length }))
    .sort((a, b) => b.score - a.score);
  const relevant = scored.filter((s) => s.score > 0).map((s) => s.theme);
  const pool = (relevant.length ? relevant : PUSH_LIBRARY).slice(0, 3);
  const examples = [];
  let i = Math.abs(Math.floor(seed)) % 997;
  while (examples.length < count && pool.length) {
    const theme = pool[examples.length % pool.length];
    examples.push({ title: theme.titles[(i * 7) % theme.titles.length], body: theme.bodies[(i * 5 + 3) % theme.bodies.length] });
    i += 3;
  }
  return examples;
};
